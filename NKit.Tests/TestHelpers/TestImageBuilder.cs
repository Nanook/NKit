            else
                File.WriteAllText(filename, GetDat("GameCube", imageName, "iso", "81753907", "9ED013B46CB985FF25653B1ECB5DF547", "336E209753CC0C82848CE4CB6247451DCC10F78A", "30784"));
        }

        internal static void ConvertImage(string srcIsoPath, string convertString)
        {
            SystemPresetSettings presets = new SystemPresetSettings()
            {
                Task = TaskType.Convert,
                Convert = convertString
            };
            presets.In.Add(srcIsoPath);
            AppSettings settings = new AppSettings(presets);
            NKitTaskResults results;
            StringBuilder logOutput = new StringBuilder();

            CancellationTokenSource cancel = new CancellationTokenSource();

            using (Log log = settings.GetLog((ms, lv) => Console.Write(ms)))
            {
                List<SourceFile> images = SourceFiles.Scan(settings.In, settings.R, settings.Arc, true, log, null).OrderBy(a => a.Name).ToList();
                NKitProcessor p = new NKitProcessor(settings, images.FirstOrDefault(), (ms, lv) => Trace.Write(logOutput.Append(ms)));

                // look at results class to see if it was successful
                results = p.Process(cancel.Token);
            }
        }

