        public static void CreateImageGcBasic(Stream stream)
        {
            //build sys files with key info used by nkit processing. Not functional images
            byte[] header = new byte[WiiConsts.BootBinSize];
            header.WriteString(WiiConsts.DataHdrIdOffset, 6, "NKITGC");
            header.WriteUInt32B(0x1c, 0xC2339F3D);
            string title = "NKit Test Dummy GameCube Image";
            header.WriteString(WiiConsts.DataHdrTitleOffset, title.Length, title);

            byte[] bi2 = new byte[WiiConsts.AppLoaderOffset - WiiConsts.BootBinSize];
            bi2.WriteUInt32B(0x18, (uint)Region.Pal);

            byte[] appldr = new byte[0x2000]; //arbitrary size
            appldr.WriteString(0, 10, new DateTime(1996, 1, 1).ToString("yyyy/MM/dd"));
            appldr.WriteUInt32B(0x14, 0x800 - 0x20); //these 2 offsets total the size of the appldr. There can be post padding. 
            appldr.WriteUInt32B(0x18, 0x1800); //We just fill it up to the maindol for ease

            int mainDolOffset = WiiConsts.AppLoaderOffset + appldr.Length;
            byte[] mainDol = new byte[0x2000]; //arbitrary size
            mainDol.WriteUInt32B(0x0, 0x100); //2 tables 7 text entries
            mainDol.WriteUInt32B(0x1c, 0x1e00); //11 data entries - set one of each to total size

            int reserveFstSize = 0x1000;
            int fstOffset = mainDolOffset + mainDol.Length;
            int filesOffset = fstOffset + reserveFstSize;

            FstBuilder fstB = new FstBuilder();
            FstDirectory fstD = fstB.AddDirectory("Subfolder");
            fstB.AddFile(filesOffset + 0x000, "File1", 0x100);
            fstD.AddFile(filesOffset + 0x100, "File2", 0x100);
            fstD.AddFile(filesOffset + 0x200, "File3", 0x100);
            fstB.AddFile(filesOffset + 0x300, "File4", 0x100);
            byte[] fst = fstB.ToArray(0, 0);

            header.WriteUInt32B(WiiConsts.DolPtrOffset, (uint)mainDolOffset);
            header.WriteUInt32B(WiiConsts.FstPtrOffset, (uint)fstOffset);
            header.WriteUInt32B(WiiConsts.FstSizeOffset, (uint)fst.Length);
            header.WriteUInt32B(WiiConsts.FstSizeMaxOffset, (uint)fst.Length);

            stream.Write(header);
            stream.Write(bi2);
            stream.Write(appldr);
            stream.Write(mainDol);
            stream.Write(fst);
            ByteStream.Zeros.Copy(stream, filesOffset - stream.Position);
            byte[] file = new byte[0x100];
            file.Clear(0, file.Length, 1);
            stream.Write(file);
            file.Clear(0, file.Length, 2);
            stream.Write(file);
            file.Clear(0, file.Length, 3);
            stream.Write(file);
            file.Clear(0, file.Length, 4);
            stream.Write(file);
        }

