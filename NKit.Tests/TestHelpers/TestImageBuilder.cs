        public static void CreateImageWiiBasic(Stream stream)
        {
            byte[] ptnHeader = new byte[0x20000];
            Array.Copy(WiiHdr, ptnHeader, WiiHdr.Length);

            WiiDiscBuilder disc = new WiiDiscBuilder(stream) { DiscId6 = "NKITWI", Title = "NKit Test Dummy Wii Image" };

            WiiPartitionBuilder ptnBuilder = disc.AddPartition(disc.DiscId6, ptnHeader, WiiConsts.WiiDefaultUpdatePtnOffset, PartitionType.Game);

            byte[] header = new byte[WiiConsts.BootBinSize];
            header.WriteString(WiiConsts.DataHdrIdOffset, disc.DiscId6.Length, disc.DiscId6);
            header.WriteUInt32B(0x1c, 0xC2339F3D);
            header.WriteString(WiiConsts.DataHdrTitleOffset, disc.Title.Length, disc.Title);

            byte[] bi2 = new byte[WiiConsts.AppLoaderOffset - WiiConsts.BootBinSize];
            bi2.WriteUInt32B(0x18, (uint)Region.Pal);

            byte[] appldr = new byte[0x2000]; //arbitrary size
            appldr.WriteString(0, 10, new DateTime(1996, 1, 1).ToString("yyyy/MM/dd"));
            appldr.WriteUInt32B(0x14, 0x800 - 0x20); //these 2 offsets total the size of the appldr. There can be post padding. 
            appldr.WriteUInt32B(0x18, 0x1800); //We just fill it up to the maindol for ease

            int mainDolOffset = WiiConsts.AppLoaderOffset + appldr.Length;
            byte[] mainDol = new byte[0x2000]; //arbitrary size
            mainDol.WriteUInt32B(0x0, 0x100); //2 tables 7 text entries
            mainDol.WriteUInt32B(0x1c, 0x1e00); //11 data entries - set one of each to total size

            ptnBuilder.SetDataHeader(header, bi2, appldr, mainDol, 0);

            Dictionary<string, byte[]> files = new Dictionary<string, byte[]>()
            {
                { "File1", createData(0x100, 1) },
                { "Subfolder/File2", createData(0x100, 2) },
                { "Subfolder/File3", createData(0x100, 3) },
                { "File4", createData(0x100, 4) }
            };

            long fsOffset = 0x8000L;
            foreach (KeyValuePair<string, byte[]> itm in files)
            {
                ptnBuilder.WriteFile(itm.Value, 0, Path.GetFileName(itm.Key), Path.GetDirectoryName(itm.Key), fsOffset, itm.Value.Length); //specific offset
                fsOffset = 4;
            }

            disc.Complete();
        }

