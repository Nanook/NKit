        {
            if (type.ToLower() == "badmd5sha1")
                File.WriteAllText(filename, GetDat("GameCube", imageName, "iso", "81753907", "BADBADBADBADBADBADBADBADBADBADBA", "BADBADBADBADBADBADBADBADBADBADBADBADBADB", "30784"));
